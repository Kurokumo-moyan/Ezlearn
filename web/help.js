// ---------------- 小圆形 ? 图标 + 提示框 ----------------
let pop = null;       // 当前提示框元素
let owner = null;     // 打开它的图标
let pinned = false;
let hideTimer = null;

function inline(text) {
  // **加粗**，其余按纯文本
  const parts = String(text).split(/(\*\*[^*]+\*\*)/g).filter(Boolean);
  return parts.map((p) => (p.startsWith('**') && p.endsWith('**') ? h('b', null, p.slice(2, -2)) : p));
}

function renderBody(item) {
  return h('div', { class: 'help-body' }, item.body.map((b) => {
    if (typeof b === 'string') return h('p', null, inline(b));
    if (b.list) return h('ul', null, b.list.map((x) => h('li', null, inline(x))));
    if (b.table) {
      return h('div', { class: 'tbl' }, h('table', null,
        h('thead', null, h('tr', null, b.table.head.map((x) => h('th', null, x)))),
        h('tbody', null, b.table.rows.map((r) => h('tr', null, r.map((c) => h('td', null, inline(c))))))));
    }
    return null;
  }));
}

function place() {
  if (!pop || !owner) return;
  const r = owner.getBoundingClientRect();
  if (!r.width && !r.height) { close(); return; }
  const w = pop.offsetWidth;
  const hgt = pop.offsetHeight;
  let left = Math.min(Math.max(8, r.left + r.width / 2 - w / 2), window.innerWidth - w - 8);
  let top = r.bottom + 8;
  if (top + hgt > window.innerHeight - 8 && r.top - hgt - 8 > 8) top = r.top - hgt - 8; // 下面放不下就放上面
  pop.style.left = `${Math.max(8, left)}px`;
  pop.style.top = `${Math.max(8, top)}px`;
}

function close() {
  clearTimeout(hideTimer);
  if (pop) pop.remove();
  if (owner) owner.setAttribute('aria-expanded', 'false');
  pop = null; owner = null; pinned = false;
}

function open(btn, key, pin) {
  const item = HELP[key];
  if (!item) return;
  clearTimeout(hideTimer);
  if (owner === btn && pop) { if (pin) { pinned = true; pop.classList.add('pinned'); } return; }
  close();
  owner = btn;
  pinned = pin;
  pop = h('div', { class: `help-pop${pin ? ' pinned' : ''}`, role: 'dialog', 'aria-label': item.title },
    h('div', { class: 'help-head' }, h('b', null, item.title), h('span', { class: 'spacer' }),
      h('button', { class: 'tp-btn help-x', title: '关闭', 'aria-label': '关闭', onclick: close }, '×')),
    renderBody(item));
  // 悬停模式下，鼠标移进提示框也不收起，方便慢慢看
  pop.addEventListener('mouseenter', () => clearTimeout(hideTimer));
  pop.addEventListener('mouseleave', () => { if (!pinned) scheduleHide(); });
  document.body.append(pop);
  btn.setAttribute('aria-expanded', 'true');
  place();
}

function scheduleHide() {
  clearTimeout(hideTimer);
  hideTimer = setTimeout(() => { if (!pinned) close(); }, 220);
}

/** 标题旁边的说明图标。 */
export function helpIcon(key) {
  const item = HELP[key];
  const btn = h('button', { class: 'help-btn', type: 'button', title: item ? `说明：${item.title}` : '说明', 'aria-label': item ? `说明：${item.title}` : '说明', 'aria-expanded': 'false' }, '?');
  let hoverTimer = null;
  btn.addEventListener('mouseenter', () => {
    if (pinned && owner !== btn) return; // 有固定显示的提示时，悬停别的图标不打扰
    clearTimeout(hideTimer);
    hoverTimer = setTimeout(() => open(btn, key, false), 120);
  });
  btn.addEventListener('mouseleave', () => { clearTimeout(hoverTimer); if (!pinned) scheduleHide(); });
  btn.addEventListener('click', (e) => {
    e.preventDefault();
    e.stopPropagation();
    clearTimeout(hoverTimer);
    if (owner === btn && pinned) close(); // 再点一次关闭
    else open(btn, key, true);
  });
  return btn;
}

// 点提示框以外的地方关闭；Esc 关闭；滚动、改变窗口大小时跟着图标走
document.addEventListener('pointerdown', (e) => {
  if (!pop) return;
  if (pop.contains(e.target) || (owner && owner.contains(e.target))) return;
  close();
}, true);
document.addEventListener('keydown', (e) => { if (e.key === 'Escape' && pop) close(); });
window.addEventListener('scroll', (e) => { if (!pop || pop.contains(e.target)) return; if (pinned) place(); else close(); }, true);
window.addEventListener('resize', () => place());
window.addEventListener('hashchange', () => close());

/** 测试 / 检查用：返回所有说明的标题。 */
export function helpKeys() { return Object.keys(HELP); }
